"""
Deterministic HPI renderer.

Takes a schema-validated HPIDraft dict and emits clinical prose via
templates. The renderer is PURE CODE — it cannot invent content,
introduce contradictions, hallucinate values, mismatch pronouns, or
write meta-commentary, because every output sentence is generated by
a function that reads only the validated input.

Renderer guarantees:
  - Every PSA value comes verbatim from draft.psa_trajectory
  - Every treatment claim comes verbatim from draft.treatment_history
  - Sex pronouns derived from draft.intro.sex (deterministic mapping)
  - No "I have followed the rules" / meta-commentary possible
  - No name placeholders (uses draft.intro.name)
  - No mid-sentence truncations (every render fn returns complete sentence)
"""
from __future__ import annotations

import re
from typing import Dict, List, Optional, Any


# ---------------------------------------------------------------------------
# Pronoun mapping
# ---------------------------------------------------------------------------

_PRONOUNS = {
    "male":   {"sub": "he",  "obj": "him", "poss": "his",  "self": "himself"},
    "female": {"sub": "she", "obj": "her", "poss": "her",  "self": "herself"},
}


def _pron(sex: str) -> Dict[str, str]:
    return _PRONOUNS.get(sex, {"sub": "the patient",
                               "obj": "the patient",
                               "poss": "the patient's",
                               "self": "themselves"})


# ---------------------------------------------------------------------------
# Date formatter
# ---------------------------------------------------------------------------

_MONTH_NAMES = ["", "January", "February", "March", "April", "May",
                "June", "July", "August", "September", "October",
                "November", "December"]


def _format_date(date_str: Optional[str]) -> str:
    """Render YYYY-MM-DD / YYYY-MM / YYYY as 'Month DD, YYYY' / 'Month YYYY' / 'YYYY'."""
    if not date_str:
        return ""
    parts = date_str.split("-")
    try:
        if len(parts) == 1:
            return parts[0]
        if len(parts) == 2:
            return f"{_MONTH_NAMES[int(parts[1])]} {parts[0]}"
        if len(parts) == 3:
            return f"{_MONTH_NAMES[int(parts[1])]} {int(parts[2])}, {parts[0]}"
    except (ValueError, IndexError):
        return date_str
    return date_str


def _date_preposition(date_str: Optional[str]) -> str:
    """Return 'on' for a specific YYYY-MM-DD, 'in' for YYYY or YYYY-MM.

    The grammar of "diagnosed in 2015" vs "diagnosed on January 7, 2026"
    matters — using "in" for a fully specified date reads as a
    template-leak."""
    if not date_str:
        return "in"
    return "on" if date_str.count("-") == 2 else "in"


